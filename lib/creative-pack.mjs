export function makeCreativeTemplates({T,C,freshBoard}) {
  return PACK_TEMPLATE_DATA.map(template => ({
    id:template.id, label:template.label, occasion:template.occasion,
    board:() => freshBoard({
      base:{...template.base}, pattern:{...template.pattern},
      elements:template.elements.map(element => {
        if(element.type==='text') { const {type,text,...options}=element;return T(text,{...options}); }
        const {type,name,...options}=element;return C(name,{...options});
      })
    })
  }));
}
